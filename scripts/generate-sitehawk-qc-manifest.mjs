import { createHash } from "node:crypto";
import { readdir, readFile, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const ROOT = process.cwd();
const TARGETS = ["src", "base44/functions", "base44/workflows", "base44/agents", "base44/entities"];
const OUT = path.join(ROOT, "base44/shared/siteHawkAppManifest.ts");
const EXCLUDED = new Set([
  "base44/shared/siteHawkAppManifest.ts",
]);

const FAMILY_RULES = [
  ["auth_admin", /auth|login|register|password|user|billing|stripe|checkout|webhook|admin|setting|deleteaccount/],
  ["legal", /hawklaw|redline|clause|legal|lease/],
  ["outreach", /mail|postcard|campaign|email|invite|notify|referral|outreach|apollo|skiptrace|ownercontact/],
  ["crm", /crm|hubspot|tracker|followup|attio|notionpush/],
  ["permits", /permit|governmentform|hawkdoc|formimport|jurisdictionresource/],
  ["scip", /scip|candidateinformationpackage/],
  ["talonfit", /talonfit|towersiter|towerfit|sitesketch|solver|frontage|residentialadjacency/],
  ["zoning", /zoning|ordinance|codehawk|municode|telecomcode|landuse|flum/],
  ["parcel", /parcel|realie|regrid|property|deed|targetabc|sitetarget|sitecandidate/],
  ["rf", /cloudrf|propagation|spectrum|coverage|fcc|celltower|towerlookup|airspace|airport/],
  ["infrastructure", /fiber|electric|power|utility|transmission|substation|transformer|hifld|peering/],
  ["environment", /fema|wetland|haz|environment|historic|tribal|species|elevation|wind|water/],
  ["maps", /map|satellite|tiles|cesium|viewshed|vision|render|photo3d/],
];

function normalize(value) {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, "");
}

function familyFor(file) {
  const normalized = normalize(file);
  for (const [family, pattern] of FAMILY_RULES) {
    if (pattern.test(normalized)) return family;
  }
  return "general";
}

async function walk(relativeDir) {
  const absoluteDir = path.join(ROOT, relativeDir);
  const entries = await readdir(absoluteDir, { withFileTypes: true }).catch(() => []);
  const files = [];
  for (const entry of entries) {
    const child = path.posix.join(relativeDir, entry.name);
    if (entry.isDirectory()) files.push(...await walk(child));
    else if (!EXCLUDED.has(child) && !child.includes("/generated/")) files.push(child);
  }
  return files;
}

const files = (await Promise.all(TARGETS.map(walk))).flat().sort();
const records = [];
for (const file of files) {
  const content = await readFile(path.join(ROOT, file));
  records.push({
    path: file,
    family: familyFor(file),
    hash: createHash("sha256").update(content).digest("hex").slice(0, 20),
  });
}

const familyMap = {};
for (const record of records) {
  (familyMap[record.family] ||= []).push(record);
}
const families = Object.fromEntries(Object.entries(familyMap).sort(([a], [b]) => a.localeCompare(b)).map(([family, rows]) => [family, {
  hash: createHash("sha256").update(rows.map((row) => `${row.path}:${row.hash}`).join("\n")).digest("hex").slice(0, 24),
  files: rows,
}]));
const fingerprint = createHash("sha256").update(records.map((row) => `${row.path}:${row.hash}`).join("\n")).digest("hex");
const output = `// Generated by scripts/generate-sitehawk-qc-manifest.mjs. Do not edit.\nexport const SITEHAWK_APP_FINGERPRINT = ${JSON.stringify(fingerprint)};\nexport const SITEHAWK_TASK_MANIFEST = ${JSON.stringify({ version: 1, fingerprint, families }, null, 2)} as const;\n`;
await mkdir(path.dirname(OUT), { recursive: true });
await writeFile(OUT, output);
console.log(`SiteHawk QC manifest: ${records.length} resources · ${Object.keys(families).length} families · ${fingerprint.slice(0, 12)}`);
